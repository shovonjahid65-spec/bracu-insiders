-- PostgreSQL is the source of truth for content, uploads and private correspondence.
CREATE TABLE admin_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(24) NOT NULL CHECK (role = 'ADMIN')
);
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(70) NOT NULL, slug VARCHAR(90) NOT NULL UNIQUE,
    section VARCHAR(16) NOT NULL CHECK (section IN ('CAMPUS','STORIES','EVENTS')),
    is_notice BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX category_names_ci ON categories (lower(name));
CREATE TABLE media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename VARCHAR(160) NOT NULL, alt_text VARCHAR(240) NOT NULL,
    mime_type VARCHAR(80) NOT NULL, bundled_path VARCHAR(200), credit VARCHAR(350),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE media_bytes (
    media_id BIGINT PRIMARY KEY REFERENCES media(id) ON DELETE CASCADE, content BYTEA NOT NULL
);
CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
    slug VARCHAR(180) NOT NULL UNIQUE, title VARCHAR(160) NOT NULL, caption VARCHAR(600) NOT NULL,
    body TEXT NOT NULL, category_id BIGINT NOT NULL REFERENCES categories(id),
    published BOOLEAN NOT NULL DEFAULT FALSE, featured BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMPTZ, updated_at TIMESTAMPTZ NOT NULL,
    source_url VARCHAR(1200), video_url VARCHAR(1200),
    event_date DATE, event_end DATE, event_info VARCHAR(150),
    CHECK (NOT published OR published_at IS NOT NULL),
    CHECK (event_end IS NULL OR (event_date IS NOT NULL AND event_end >= event_date))
);
CREATE INDEX posts_feed ON posts (published, published_at DESC, id DESC);
CREATE INDEX posts_events ON posts (event_date) WHERE published;
CREATE TABLE post_media (
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    position INTEGER NOT NULL, media_id BIGINT NOT NULL REFERENCES media(id),
    PRIMARY KEY(post_id, position)
);
CREATE INDEX post_media_asset ON post_media(media_id);
CREATE TABLE post_reads (
    post_id BIGINT PRIMARY KEY REFERENCES posts(id) ON DELETE CASCADE, views BIGINT NOT NULL DEFAULT 1
);
CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name VARCHAR(80) NOT NULL, email VARCHAR(254), subject VARCHAR(140) NOT NULL,
    body TEXT NOT NULL, receipt_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE,
    archived BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX messages_inbox ON messages(archived, created_at DESC);
CREATE TABLE message_files (
    message_id BIGINT PRIMARY KEY REFERENCES messages(id) ON DELETE CASCADE,
    filename VARCHAR(160) NOT NULL, mime_type VARCHAR(80) NOT NULL, content BYTEA NOT NULL
);
CREATE TABLE replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    body TEXT NOT NULL, sent_at TIMESTAMPTZ NOT NULL, author VARCHAR(80) NOT NULL
);
CREATE INDEX replies_thread ON replies(message_id, sent_at);
CREATE TABLE site_settings (
    id BIGINT PRIMARY KEY CHECK (id = 1), version BIGINT NOT NULL DEFAULT 0,
    site_name VARCHAR(70) NOT NULL, tagline VARCHAR(140) NOT NULL,
    email VARCHAR(254) NOT NULL, facebook_url VARCHAR(600)
);
CREATE TABLE desk_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor VARCHAR(80) NOT NULL,
    summary VARCHAR(220) NOT NULL, occurred_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX desk_activity_recent ON desk_activity(occurred_at DESC);
CREATE TABLE app_state (key_name VARCHAR(64) PRIMARY KEY, value_text VARCHAR(160) NOT NULL);
CREATE TABLE rate_windows (
    key_hash CHAR(64) NOT NULL, bucket BIGINT NOT NULL, hits INTEGER NOT NULL,
    PRIMARY KEY(key_hash,bucket)
);
CREATE INDEX rate_windows_expiry ON rate_windows(bucket);
